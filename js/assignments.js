document.getElementById('save-task-btn').addEventListener('click', async () => {
    const id = document.getElementById('task-id').value;
    const subId = document.getElementById('task-course').value;
    const title = document.getElementById('task-name').value.trim();
    const dDate = document.getElementById('task-date').value;
    const dTime = document.getElementById('task-time').value || '23:59';
    
    if(!subId || !title || !dDate) return alert("Course, Name, and Date are required.");
    const fullDate = new Date(`${dDate}T${dTime}`).toISOString();
    
    const payload = {
        subject_id: subId,
        title: title,
        due_date: fullDate,
        status: document.getElementById('task-status').value,
        link: document.getElementById('task-link').value.trim(),
        notes: document.getElementById('task-notes').value.trim(),
        tags: Array.from(currentSidebarTags)
    };

    if(id) await supabaseClient.from('assignments').update(payload).eq('id', id);
    else await supabaseClient.from('assignments').insert([payload]);
    
    closeTaskSidebar();
    fetchTermData(window.AcadState.activeTerm.id);
});

