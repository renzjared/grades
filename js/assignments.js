window.AcadState = {
    terms: [],
    activeTerm: null,
    termTags: [],
    subjects: [],
    assignments: [],
    classes: [],
    visibleSubjects: new Set(),
    selectedTags: new Set(),
    searchQuery: '',
    sortOrder: 'date_added'
};

async function renderAssignmentsView() {
    if (!currentUser) {
        document.getElementById('auth-modal').classList.remove('hidden');
        switchView('explore');
        return;
    }
    await fetchTerms();
}

async function fetchTerms() {
    const { data: terms } = await supabaseClient.from('terms').select('*').eq('user_id', currentUser.id).order('created_at', { ascending: false });
    window.AcadState.terms = terms || [];
    
    const selector = document.getElementById('sidebar-term-selector');
    
    if (terms && terms.length > 0) {
        if(!window.AcadState.activeTerm) window.AcadState.activeTerm = terms[0];
        window.AcadState.termTags = window.AcadState.activeTerm.tags || [];
        window.AcadState.selectedTags.clear();

        selector.innerHTML = terms.map(t => `<option value="${t.id}" ${window.AcadState.activeTerm.id === t.id ? 'selected' : ''}>${t.name}</option>`).join('');
        selector.disabled = false;
        await fetchTermData(window.AcadState.activeTerm.id);
    } else {
        selector.innerHTML = `<option>No terms yet</option>`;
        selector.disabled = true;
        document.getElementById('assignments-body').innerHTML = '<tr><td colspan="5" style="text-align:center;">Create a new term to start tracking assignments.</td></tr>';
    }
}

async function fetchTermData(termId) {
    const { data: subjects } = await supabaseClient.from('subjects').select('*').eq('term_id', termId).order('name', { ascending: true });
    window.AcadState.subjects = subjects || [];
    window.AcadState.visibleSubjects = new Set(window.AcadState.subjects.map(s => s.id));
    
    if (subjects && subjects.length > 0) {
        const subIds = subjects.map(s => s.id);
        const { data: assignments } = await supabaseClient.from('assignments').select('*').in('subject_id', subIds);
        window.AcadState.assignments = assignments || [];

        const { data: classes } = await supabaseClient.from('class_instances').select('*').in('subject_id', subIds);
        window.AcadState.classes = classes || [];
    } else {
        window.AcadState.assignments = [];
        window.AcadState.classes = [];
    }

    updateUI();
}

