window.toggleSubjectVisible = (subId, isVisible) => {
    if (isVisible) window.AcadState.visibleSubjects.add(subId);
    else window.AcadState.visibleSubjects.delete(subId);
    renderBentoAndTable();
    if(typeof renderCalendarView === 'function') renderCalendarView();
};

window.toggleTagFilter = (tagId, isVisible) => {
    if (isVisible) window.AcadState.selectedTags.add(tagId);
    else window.AcadState.selectedTags.delete(tagId);
    renderBentoAndTable();
};

function renderBentoAndTable() {
    const now = new Date();
    let urgent = 0, overdue = 0, inProgress = 0;
    
    let filteredTasks = window.AcadState.assignments.filter(a => {
        if (!window.AcadState.visibleSubjects.has(a.subject_id)) return false;
        if (window.AcadState.searchQuery && !a.title.toLowerCase().includes(window.AcadState.searchQuery.toLowerCase())) return false;
        if (window.AcadState.selectedTags.size > 0) {
            let taskTags = a.tags || [];
            let matches = taskTags.some(tId => window.AcadState.selectedTags.has(tId));
            if (!matches) return false;
        }
        return true;
    });

    filteredTasks.sort((a, b) => {
        if (window.AcadState.sortOrder === 'date_added') return new Date(b.created_at || 0) - new Date(a.created_at || 0);
        if (window.AcadState.sortOrder === 'date_asc') return new Date(a.due_date) - new Date(b.due_date);
        if (window.AcadState.sortOrder === 'date_desc') return new Date(b.due_date) - new Date(a.due_date);
        if (window.AcadState.sortOrder === 'status') return (a.status || 'not_started').localeCompare(b.status || 'not_started');
        return 0;
    });

    const tbody = document.getElementById('assignments-body');
    let html = '';

    filteredTasks.forEach(a => {
        const sub = window.AcadState.subjects.find(s => s.id === a.subject_id);
        const due = new Date(a.due_date);
        const diffHours = (due - now) / (1000 * 60 * 60);

        if (a.status === 'in_progress') inProgress++;
        if (a.status === 'not_started' || a.status === 'in_progress' || !a.status) {
            if (diffHours < 0) overdue++;
            else if (diffHours <= 48) urgent++;
        }

        let taskTags = a.tags || [];
        let tagHtml = taskTags.map(tId => {
            let tagConf = window.AcadState.termTags.find(x => x.id === tId);
            if (!tagConf) return '';
            return `<span class="tag-pill" style="background:${tagConf.color}; color:${window.getContrastYIQ(tagConf.color)}; margin-right:4px;">${tagConf.name}</span>`;
        }).join('');

        html += `
        <tr class="status-${a.status || 'not_started'}">
            <td>
                <select class="input-minimal status-select" onchange="updateTaskStatus('${a.id}', this.value)">
                    <option value="not_started" ${a.status==='not_started'?'selected':''}>Not Started</option>
                    <option value="in_progress" ${a.status==='in_progress'?'selected':''}>In Progress</option>
                    <option value="completed" ${a.status==='completed'?'selected':''}>Completed</option>
                    <option value="dropped" ${a.status==='dropped'?'selected':''}>Dropped</option>
                    <option value="cancelled" ${a.status==='cancelled'?'selected':''}>Cancelled</option>
                </select>
            </td>
            <td>
                <div style="font-weight:600; font-size:0.85rem;">${due.toLocaleDateString(undefined, {month:'short', day:'numeric'})}</div>
                <div style="font-size:0.75rem; color:var(--text-muted);">${due.toLocaleTimeString(undefined, {hour:'2-digit', minute:'2-digit'})}</div>
            </td>
            <td><span class="stat-pill" style="color:${sub.color}; background:${sub.color}1a;">${window.renderSubjectIcon(sub.icon)} ${sub.code}</span></td>
            <td>
                <div style="font-weight:500; cursor:pointer; margin-bottom:4px;" onclick="openTaskSidebar('${a.id}')">${a.title}</div>
                <div>${tagHtml}</div>
            </td>
            <td>
                <div style="display:flex; gap:0.5rem; justify-content:flex-end;">
                    ${a.link ? `<a href="${a.link}" target="_blank" class="action-icon" style="color:var(--text-main); text-decoration:none;" title="Open Link"><svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M18 13v6a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2V8a2 2 0 0 1 2-2h6"></path><polyline points="15 3 21 3 21 9"></polyline><line x1="10" y1="14" x2="21" y2="3"></line></svg></a>` : '<div style="width:20px;"></div>'}
                    <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" class="action-icon edit-icon" onclick="openTaskSidebar('${a.id}')" title="Edit Task"><path d="M11 4H4a2 2 0 0 0-2 2v14a2 2 0 0 0 2 2h14a2 2 0 0 0 2-2v-7"></path><path d="M18.5 2.5a2.121 2.121 0 0 1 3 3L12 15l-4 1 1-4 9.5-9.5z"></path></svg>
                    <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="#e53e3e" stroke-width="2" class="action-icon delete-icon" onclick="openDeleteConfirm('${a.id}')" title="Delete Task"><polyline points="3 6 5 6 21 6"></polyline><path d="M19 6v14a2 2 0 0 1-2 2H7a2 2 0 0 1-2-2V6m3 0V4a2 2 0 0 1 2-2h4a2 2 0 0 1 2 2v2"></path></svg>
                </div>
            </td>
        </tr>`;
    });

    tbody.innerHTML = html || '<tr><td colspan="5" style="text-align:center;">No tasks found.</td></tr>';

    document.getElementById('bento-urgent').innerText = urgent;
    document.getElementById('bento-overdue').innerText = overdue;
    document.getElementById('bento-progress').innerText = inProgress;
    document.getElementById('bento-total').innerText = filteredTasks.length;
}

window.updateTaskStatus = async (taskId, newStatus) => {
    await supabaseClient.from('assignments').update({ status: newStatus }).eq('id', taskId);
    const t = window.AcadState.assignments.find(a => a.id === taskId);
    if(t) t.status = newStatus;
    renderBentoAndTable();
};

